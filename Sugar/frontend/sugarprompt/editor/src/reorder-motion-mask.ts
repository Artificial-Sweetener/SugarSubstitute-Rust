/** Supported native attributes suppress only admitted complete passive chip paint, never native layout. */
import { StateEffect } from '@codemirror/state';
import type { NativeReorderCapture } from './reorder-command.js';
/** One exact display lease owns a bounded native opacity mask. */
export interface ReorderMotionMask {
  readonly issue: object;
  /** Stable finite CSS scope never substitutes for exact issue-owned currentness or release. */
  readonly scope: object;
  readonly capture: NativeReorderCapture;
  readonly ids: readonly number[];
  /** Complete pointer coverage masks its stable hard-line underlay, independently of the animated-ID cap. */
  readonly coverage?: 'value';
}
/** Publication and exact-owned retirement never change document or history. */
export const setReorderMotionMask = StateEffect.define<ReorderMotionMask>();
/** A stale release cannot reveal chips masked by a newer accepted display lease. */
export const releaseReorderMotionMask = StateEffect.define<object>();
