//! Own the original witness Finish nonce and final response under one immutable cutoff.
use super::*;
use sugarsubstitute_execution::windows_lifecycle_pipe::LifecyclePipeDeadline;

/// The original tuple's same fixed semantic storage; transport ownership stays in State.
pub(super) struct Finish {
    until: Moment,
    nonce: Option<u64>,
    completed: bool,
}
/// Borrow the actual transaction slots without copying an owner or admitting capacity.
pub(super) struct Exchange<'a> {
    pub(super) next_nonce: &'a mut u64,
    pub(super) pending: &'a mut Option<(BackendCustodyFrame, Moment)>,
    pub(super) receipt: &'a mut Option<ReceiptFacts>,
    pub(super) io_pending: bool,
}
/// Distinguish final fact consumption from the one newly queued native transaction.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(super) enum Progress {
    Waiting,
    Queued,
    Finished,
}
impl Finish {
    /// Freeze one original cutoff before observing or queueing its response.
    pub(super) fn new(until: Moment) -> Self {
        Self { until, nonce: None, completed: false }
    }
    /// Borrow the nonce generated by this original semantic request owner.
    pub(super) fn nonce(&self) -> Option<u64> {
        self.nonce
    }
    /// Advance the actual semantic transaction; the external port authorizes fresh effects.
    /// # Errors
    /// Preserves admission causes and rejects renewed cutoffs or changed final correlation.
    pub(super) fn advance(
        &mut self,
        key: BackendCustodyKey,
        until: Moment,
        exchange: Exchange<'_>,
        admit: impl FnOnce() -> Result<LifecyclePipeDeadline, NativeObservationError>,
    ) -> Result<Progress, NativeObservationError> {
        if self.until != until {
            return Err(reject("custody_finish_renewed"));
        }
        if self.completed {
            return Ok(Progress::Finished);
        }
        if let Some(facts) = *exchange.receipt {
            if facts.key != key {
                return Err(reject("custody_finish_key"));
            }
            if self.nonce == Some(facts.nonce)
                && facts.receipt.expand(facts.key.owner()) == BackendCustodyReceipt::Finished
            {
                if exchange.io_pending || exchange.pending.is_some() {
                    return Ok(Progress::Waiting);
                }
                *exchange.receipt = None;
                self.completed = true;
                return Ok(Progress::Finished);
            }
            if self.nonce.is_some() {
                return Err(reject("custody_finish_receipt"));
            }
        }
        let counter = admit()?;
        if self.nonce.is_none()
            && exchange.pending.is_none()
            && exchange.receipt.is_none()
            && !exchange.io_pending
        {
            let nonce =
                exchange.next_nonce.checked_add(1).ok_or_else(|| reject("custody_parent_nonce"))?;
            *exchange.next_nonce = nonce;
            *exchange.pending = Some((
                BackendCustodyFrame {
                    key,
                    nonce,
                    command: BackendCustodyCommand::Finish {
                        until_ticks: counter.ticks(),
                        frequency: counter.frequency(),
                    },
                },
                until,
            ));
            self.nonce = Some(nonce);
            tracing::info!(operation="backend_custody_finish_queued", key=?key, nonce, until=?until,
                "Original Finish transaction retained for native issue");
            return Ok(Progress::Queued);
        }
        Ok(Progress::Waiting)
    }
}

