/** Model unsupported CSS capability queries in JSDOM's browser boundary. */
if (typeof CSS === 'undefined') {
  Object.defineProperty(globalThis, 'CSS', {
    configurable: true,
    value: { supports: (_property: string, _value?: string): boolean => false },
  });
}
